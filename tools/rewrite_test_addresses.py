@dataclass
class Edit:
    start: int
    end: int
    replacement: str


def apply_edits(text: str, edits: list[Edit]) -> str:
    for edit in sorted(edits, key=lambda e: e.start, reverse=True):
        text = text[: edit.start] + edit.replacement + text[edit.end :]
    return text


# ---------------------------------------------------------------------------
# Docstrings (excluded from the string-constant scan/rewrite)
# ---------------------------------------------------------------------------


def docstring_node_ids(tree: ast.Module) -> set[int]:
    ids: set[int] = set()
    for node in ast.walk(tree):
        body = getattr(node, "body", None)
        if (
            isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef))
            and body
        ):
            first = body[0]
            if (
                isinstance(first, ast.Expr)
                and isinstance(first.value, ast.Constant)
                and isinstance(first.value.value, str)
            ):
                ids.add(id(first.value))
    return ids


def simple_string_body_span(
    idx: SourceIndex, text: str, node: ast.Constant
) -> tuple[int, int, str] | None:
    """Locate the exact char span of a Constant string's BODY (between its
    quotes), only for a single, non-f, non-concatenated literal whose
    ``ast.literal_eval`` round-trips to ``node.value`` exactly. Anything else
    (implicit concatenation, f-strings, exotic escapes) returns ``None`` --
    reported, never guessed."""
    seg_start = idx.linecol_to_char(node.lineno, node.col_offset)
    seg_end = idx.linecol_to_char(node.end_lineno, node.end_col_offset)
    seg = text[seg_start:seg_end]
    m = _SIMPLE_STRING_RE.match(seg)
    if not m:
        return None
    prefix = m.group("prefix").lower()
    if "f" in prefix:
        return None
    try:
        decoded = ast.literal_eval(seg)
    except (ValueError, SyntaxError):
        return None
    if decoded != node.value:
        return None
    body_start = seg_start + m.start("body")
    body_end = seg_start + m.end("body")
    return body_start, body_end, m.group("body")


def _char_index_within(segment_text: str, row: int, col: int) -> int:
    """``row`` (1-based) / ``col`` (0-based char, not byte) as reported by the
    stdlib ``tokenize`` module -- which operates on the decoded str, so both
    are already char offsets, unlike ``ast``'s byte ``col_offset``."""
    lines = segment_text.splitlines(keepends=True)
    return sum(len(line) for line in lines[: row - 1]) + col


def string_literal_segments(
    idx: SourceIndex, text: str, node: ast.Constant
) -> list[tuple[int, int, str]] | None:
    """Yield ``(body_start_char, body_end_char, body_text)`` for every
    individual quoted string literal token inside ``node``'s span, handling
    IMPLICIT ADJACENT-LITERAL CONCATENATION (``"a" "b"``) by tokenizing the
    node's own source segment rather than treating it as one literal.
    Returns ``None`` (report, never guess) if any token is an f-string, is
    not a plain string literal, or fails to round-trip through
    ``ast.literal_eval`` -- the same conservative contract as
    :func:`simple_string_body_span`. KNOWN LIMITATION: an old address split
    across a literal boundary (e.g. ``"entropic_substr" "ate.x"``) would not
    be found, since each segment is scanned independently; this pattern does
    not occur in this codebase."""
    seg_start = idx.linecol_to_char(node.lineno, node.col_offset)
    seg_end = idx.linecol_to_char(node.end_lineno, node.end_col_offset)
    segment_text = text[seg_start:seg_end]
    try:
        tokens = list(tokenize.generate_tokens(io.StringIO(segment_text).readline))
    except (tokenize.TokenError, SyntaxError, IndentationError):
        return None
    results: list[tuple[int, int, str]] = []
    for tok in tokens:
        if tok.type != tokenize.STRING:
            continue
        raw = tok.string
        m = _SIMPLE_STRING_RE.match(raw)
        if not m:
            return None
        if "f" in m.group("prefix").lower():
            return None
        try:
            decoded = ast.literal_eval(raw)
        except (ValueError, SyntaxError):
            return None
        tok_start_char = seg_start + _char_index_within(segment_text, *tok.start)
        body_start = tok_start_char + m.start("body")
        body_end = tok_start_char + m.end("body")
        if text[body_start:body_end] != m.group("body"):
            return None  # defensive: offset arithmetic disagreement, never guess
        results.append((body_start, body_end, m.group("body")))
        del decoded  # only used to validate round-trip above
    if not results:
        return None
    return results


def longest_shim_prefix(chain: str, shims: ShimMap) -> tuple[str, str] | None:
    """``chain`` is a dot-joined run starting with ``entropic_substrate``.
    Returns ``(matched_prefix, target)`` for the LONGEST dot-boundary prefix
    that is a shim key, or ``None``."""
    parts = chain.split(".")
    for k in range(len(parts), 1, -1):
        candidate = ".".join(parts[:k])
        if candidate in shims:
            return candidate, shims[candidate]
    return None


