@dataclass
class Residual:
    path: str
    line: int
    chain: str
    category: str  # SKIP | BY_NAME | RULED | EXCLUSION_DEF | UNLISTED


@dataclass
class VerifyReport:
    residuals: list[Residual] = field(default_factory=list)

    def unlisted(self) -> list[Residual]:
        return [r for r in self.residuals if r.category == "UNLISTED"]


def _exclusion_def_node_ids(tree: ast.Module) -> set[int]:
    ids: set[int] = set()
    for node in tree.body:
        if isinstance(node, ast.Assign):
            targets = [t.id for t in node.targets if isinstance(t, ast.Name)]
            if any(t in EXCLUSION_TABLE_NAMES for t in targets):
                for sub in ast.walk(node.value):
                    ids.add(id(sub))
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            if node.target.id in EXCLUSION_TABLE_NAMES and node.value is not None:
                for sub in ast.walk(node.value):
                    ids.add(id(sub))
    return ids


def classify(rel: str, line: int, chain: str, mode: str, in_exclusion_def: bool) -> str:
    if in_exclusion_def:
        return "EXCLUSION_DEF"
    if mode == "b1" and rel in SKIP_LIST_B1:
        return "SKIP"
    if rel in NAMESPACE_EXCLUSIONS:
        return "BY_NAME"
    if chain in WIRE_VALUE_EXCLUSIONS:
        return "BY_NAME"
    ruled_lines = RULED_B2_SITES.get(rel, frozenset())
    if line in ruled_lines:
        return "RULED"
    return "UNLISTED"


def scan_python_file(root: Path, path: Path, mode: str) -> list[Residual]:
    rel = relpath(root, path)
    try:
        text = path.read_text(encoding="utf-8")
    except (UnicodeDecodeError, OSError):
        return []
    try:
        tree = ast.parse(text, filename=str(path))
    except SyntaxError:
        return [Residual(rel, 0, "<SyntaxError>", "UNLISTED")]
    doc_ids = docstring_node_ids(tree)
    excl_ids = _exclusion_def_node_ids(tree)
    residuals: list[Residual] = []

    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                name = alias.name
                if name == "entropic_substrate" or not name.startswith("entropic_substrate."):
                    continue
                if not is_old_seg(name.split(".")[1]):
                    continue
                cat = classify(rel, alias.lineno, name, mode, id(alias) in excl_ids)
                residuals.append(Residual(rel, alias.lineno, name, cat))
        elif isinstance(node, ast.ImportFrom):
            if node.level and node.level > 0:
                continue
            module = node.module or ""
            if module == "entropic_substrate":
                for alias in node.names:
                    if alias.name == "*" or is_old_seg(alias.name):
                        chain = f"entropic_substrate import {alias.name}"
                        cat = classify(rel, node.lineno, chain, mode, id(node) in excl_ids)
                        residuals.append(Residual(rel, node.lineno, chain, cat))
            elif module.startswith("entropic_substrate."):
                if is_old_seg(module.split(".")[1]):
                    cat = classify(rel, node.lineno, module, mode, id(node) in excl_ids)
                    residuals.append(Residual(rel, node.lineno, module, cat))
        elif isinstance(node, ast.Constant) and isinstance(node.value, str):
            if id(node) in doc_ids:
                continue
            in_def = id(node) in excl_ids
            for m in CHAIN_RE.finditer(node.value):
                chain = m.group(0)
                parts = chain.split(".")
                if len(parts) < 2 or not is_old_seg(parts[1]):
                    continue
                cat = classify(rel, node.lineno, chain, mode, in_def)
                residuals.append(Residual(rel, node.lineno, chain, cat))
            for m in ROOT_FROM_IMPORT_RE.finditer(node.value):
                seg = m.group(1)
                if not is_old_seg(seg):
                    continue
                chain = m.group(0)
                cat = classify(rel, node.lineno, chain, mode, in_def)
                residuals.append(Residual(rel, node.lineno, chain, cat))
    return residuals


def scan_nonpython_file(root: Path, path: Path, mode: str) -> list[Residual]:
    rel = relpath(root, path)
    try:
        text = path.read_text(encoding="utf-8")
    except (UnicodeDecodeError, OSError):
        return []
    residuals: list[Residual] = []
    for lineno, line in enumerate(text.splitlines(), start=1):
        stripped = line.lstrip()
        if stripped.startswith("#"):
            continue
        for m in CHAIN_RE.finditer(line):
            chain = m.group(0)
            parts = chain.split(".")
            if len(parts) < 2 or not is_old_seg(parts[1]):
                continue
            cat = classify(rel, lineno, chain, mode, in_exclusion_def=False)
            residuals.append(Residual(rel, lineno, chain, cat))
        for m in ROOT_FROM_IMPORT_RE.finditer(line):
            seg = m.group(1)
            if not is_old_seg(seg):
                continue
            chain = m.group(0)
            cat = classify(rel, lineno, chain, mode, in_exclusion_def=False)
            residuals.append(Residual(rel, lineno, chain, cat))
    return residuals


def cmd_verify(args: argparse.Namespace) -> int:
    root = Path(args.root).resolve()
    mode = args.mode
    if args.paths:
        py_paths = [Path(p) for p in args.paths]
        nonpy_paths: list[Path] = []
    elif mode == "b1":
        py_paths = [root / p for p in DEFAULT_B1_SCOPE]
        nonpy_paths = []
    else:
        py_paths = [root / p for p in DEFAULT_B2_PY_SCOPE]
        nonpy_paths = [root / p for p in DEFAULT_B2_NONPY_SURFACES if (root / p).exists()]

    report = VerifyReport()
    py_files: list[Path] = []
    for p in py_paths:
        if not p.exists():
            continue
        if p.is_dir():
            py_files.extend(sorted(p.rglob("*.py")))
        else:
            py_files.append(p)
    seen: set[Path] = set()
    for f in py_files:
        if "__pycache__" in f.parts:
            continue
        rf = f.resolve()
        if rf in seen:
            continue
        seen.add(rf)
        report.residuals.extend(scan_python_file(root, f, mode))

    for f in nonpy_paths:
        if f.is_file():
            report.residuals.extend(scan_nonpython_file(root, f, mode))

    by_file: dict[str, list[Residual]] = {}
    for r in report.residuals:
        by_file.setdefault(r.path, []).append(r)

    for path in sorted(by_file):
        rows = by_file[path]
        counts: dict[str, int] = {}
        for r in rows:
            counts[r.category] = counts.get(r.category, 0) + 1
        print(f"{path}: {counts}")
        for r in rows:
            if r.category == "UNLISTED":
                print(f"    UNLISTED {r.path}:{r.line}: {r.chain}")

    unlisted = report.unlisted()
    print(f"--- mode={mode}: {len(report.residuals)} residual(s), {len(unlisted)} UNLISTED ---")
    return 1 if unlisted else 0


