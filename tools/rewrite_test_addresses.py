LANDED_TOP_SEGMENTS = frozenset({"kernel", "core", "ladder", "historical", "composition"})
# __main__ is the root entrypoint, not a layer, but is likewise never "old".
LANDED_OR_ROOT_SEGMENTS = LANDED_TOP_SEGMENTS | {"__main__"}
_DUNDER_RE = re.compile(r"^__[a-z]+__$")

MARKER_RE = re.compile(r"^# Generated by gen_shims\.py from .+-- do not hand-edit\.\s*$")

_IDENT = r"[A-Za-z_][A-Za-z0-9_]*"
# Unanchored chain finder: a run of dot-joined identifiers starting at a
# non-identifier/non-dot boundary, rooted at "entropic_substrate".
CHAIN_RE = re.compile(rf"(?<![A-Za-z0-9_.])entropic_substrate(?:\.{_IDENT})*")
# The second string/line pattern (P13-NAMESPACE-RULE addendum 2): the root
# "from entropic_substrate import <seg>" form embedded in text (e.g. a
# subprocess source string), never auto-rewritten by apply (composing the
# correct replacement can require an alias this tool will not guess).
ROOT_FROM_IMPORT_RE = re.compile(
    rf"(?<![A-Za-z0-9_.])from\s+entropic_substrate\s+import\s+({_IDENT})"
)

# A simple (non-f, non-concatenated) string literal: optional prefix, a
# matching quote pair, body, same quote. DOTALL for triple-quoted bodies.
_SIMPLE_STRING_RE = re.compile(
    r"^(?P<prefix>[a-zA-Z]{0,2})(?P<quote>'''|\"\"\"|'|\")(?P<body>.*)(?P=quote)$",
    re.DOTALL,
)

# Names of the module-level constants that DEFINE the exclusion machinery.
# A match found inside the literal that defines one of these (e.g. when this
# tool's own source is the scan target) is EXCLUSION_DEF, never UNLISTED.
EXCLUSION_TABLE_NAMES = frozenset(
    {"SKIP_LIST_B1", "NAMESPACE_EXCLUSIONS", "WIRE_VALUE_EXCLUSIONS", "RULED_B2_SITES"}
)


def is_old_seg(seg: str) -> bool:
    """A segment is OLD iff it is not a landed layer / root name and is not a
    dunder (``__[a-z]+__``): ``entropic_substrate.__file__`` is an attribute,
    never an address (P13-NAMESPACE-RULE addendum 3); ``__no_such_module__``
    and ``__legacy`` both fail the dunder fullmatch and ARE flagged."""
    if seg in LANDED_OR_ROOT_SEGMENTS:
        return False
    if _DUNDER_RE.fullmatch(seg):
        return False
    return True


