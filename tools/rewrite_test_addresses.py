ShimMap = dict[str, str]
# facade dotted package -> {exported name -> (source module, original name)}
FacadeMap = dict[str, dict[str, tuple[str, str]]]


def _module_dotted_address(pkg_root: Path, pyfile: Path) -> str:
    rel = pyfile.relative_to(pkg_root.parent)
    parts = list(rel.with_suffix("").parts)
    if parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


def _find_target_alias(tree: ast.Module) -> str | None:
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.asname == "_target":
                    return alias.name
    return None


def _find_runpy_target(tree: ast.Module) -> str | None:
    for node in ast.walk(tree):
        if (
            isinstance(node, ast.Call)
            and isinstance(node.func, ast.Attribute)
            and node.func.attr == "run_module"
            and isinstance(node.func.value, ast.Name)
            and node.func.value.id == "runpy"
            and node.args
            and isinstance(node.args[0], ast.Constant)
            and isinstance(node.args[0].value, str)
        ):
            return node.args[0].value
    return None


def discover_shims(src_root: Path) -> ShimMap:
    pkg_root = src_root / "entropic_substrate"
    shims: ShimMap = {}
    for pyfile in sorted(pkg_root.rglob("*.py")):
        if "__pycache__" in pyfile.parts:
            continue
        try:
            text = pyfile.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        first_line = text.splitlines()[0] if text else ""
        if not MARKER_RE.match(first_line):
            continue
        try:
            tree = ast.parse(text, filename=str(pyfile))
        except SyntaxError:
            continue
        target = _find_target_alias(tree)
        if target is None:
            continue
        old_addr = _module_dotted_address(pkg_root, pyfile)
        shims[old_addr] = target
        if "runpy.run_module(" in text:
            runpy_target = _find_runpy_target(tree)
            if runpy_target is not None and runpy_target != target:
                raise MapDerivationError(
                    f"entrypoint shim disagreement at {pyfile}: "
                    f"import target {target!r} != runpy.run_module target {runpy_target!r}"
                )
    return shims


def discover_facades(src_root: Path) -> FacadeMap:
    pkg_root = src_root / "entropic_substrate"
    facades: FacadeMap = {}
    if not pkg_root.is_dir():
        return facades
    for child in sorted(pkg_root.iterdir()):
        if not child.is_dir() or child.name.startswith("__pycache__"):
            continue
        name = child.name
        if name in LANDED_TOP_SEGMENTS or name == "__legacy":
            continue
        init_file = child / "__init__.py"
        if not init_file.is_file():
            continue
        try:
            text = init_file.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        first_line = text.splitlines()[0] if text else ""
        if MARKER_RE.match(first_line):
            continue  # a generated shim __init__.py, not a hand-written facade
        try:
            tree = ast.parse(text, filename=str(init_file))
        except SyntaxError:
            continue
        reexports: dict[str, tuple[str, str]] = {}
        has_reexport = False
        for node in tree.body:
            if (
                isinstance(node, ast.ImportFrom)
                and node.level == 0
                and node.module
                and node.module.startswith("entropic_substrate.")
            ):
                has_reexport = True
                for alias in node.names:
                    if alias.name == "*":
                        continue
                    exported = alias.asname or alias.name
                    reexports[exported] = (node.module, alias.name)
        if has_reexport:
            facades[f"entropic_substrate.{name}"] = reexports
    if len(facades) != 7:
        raise MapDerivationError(
            f"expected exactly 7 restored facades (P13-FACADE-NAMES), found "
            f"{len(facades)}: {sorted(facades)}"
        )
    return facades


def build_map(root: Path) -> tuple[ShimMap, FacadeMap]:
    src_root = root / "src"
    shims = discover_shims(src_root)
    facades = discover_facades(src_root)
    return shims, facades


# ---------------------------------------------------------------------------
# Per-name resolution for "from <pkg> import name" (root or facade pkg)
# ---------------------------------------------------------------------------


@dataclass
class NameResolution:
    kind: str  # "submodule" | "symbol"
    target_module: (
        str  # for "submodule": the PARENT of the target; for "symbol": the full target module
    )
    leaf: str  # for "submodule": the target's own last segment; for "symbol": the original symbol name


def resolve_name(
    pkg: str, name: str, shims: ShimMap, facades: FacadeMap
) -> NameResolution | tuple[None, str]:
    """Resolve a single ``from <pkg> import <name>``. Returns a
    ``NameResolution`` on success, or ``(None, reason)`` on failure."""
    combo = f"{pkg}.{name}"
    is_shim_submodule = combo in shims
    is_facade_reexport = pkg in facades and name in facades[pkg]
    if is_shim_submodule and is_facade_reexport:
        return (
            None,
            f"ambiguous: {combo!r} is both a shimmed submodule and a facade re-export",
        )
    if is_shim_submodule:
        target = shims[combo]
        parent, _, leaf = target.rpartition(".")
        return NameResolution("submodule", parent, leaf)
    if is_facade_reexport:
        source_module, original_name = facades[pkg][name]
        if source_module not in shims:
            return (
                None,
                f"facade re-export {combo!r} -> {source_module!r} has no shim",
            )
        target = shims[source_module]
        return NameResolution("symbol", target, original_name)
    return (None, f"{combo!r} resolves through no shim and no facade re-export")


# ---------------------------------------------------------------------------
# Source-position bookkeeping (byte col_offset -> char index)
# ---------------------------------------------------------------------------


class SourceIndex:
    def __init__(self, text: str) -> None:
        self._lines = text.splitlines(keepends=True)
        self._line_start_char: list[int] = []
        pos = 0
        for line in self._lines:
            self._line_start_char.append(pos)
            pos += len(line)
        self._total = pos

    def linecol_to_char(self, lineno: int, byte_col: int) -> int:
        line = self._lines[lineno - 1] if lineno - 1 < len(self._lines) else ""
        encoded = line.encode("utf-8")
        char_col = len(encoded[:byte_col].decode("utf-8"))
        base = (
            self._line_start_char[lineno - 1]
            if lineno - 1 < len(self._line_start_char)
            else self._total
        )
        return base + char_col


