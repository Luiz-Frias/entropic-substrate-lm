def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)

    p_apply = sub.add_parser("apply", help="rewrite old addresses onto landed ones")
    p_apply.add_argument("--root", default=".")
    p_apply.add_argument("paths", nargs="+")
    p_apply.set_defaults(func=cmd_apply)

    p_verify = sub.add_parser("verify", help="scan for residual old addresses")
    p_verify.add_argument("--root", default=".")
    p_verify.add_argument("--mode", choices=["b1", "b2"], required=True)
    p_verify.add_argument("paths", nargs="*")
    p_verify.set_defaults(func=cmd_verify)

    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    return int(args.func(args))


if __name__ == "__main__":
    raise SystemExit(main())
