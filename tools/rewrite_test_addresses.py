#!/usr/bin/env python3
"""One-shot rewrite tool for p13-sweep commit B1 (P13-TOOLS, P13-FACADE-NAMES).

Rewrites every consumer of the RETIRED dotted namespace (`entropic_substrate.<old>`)
onto its landed address. The old-to-landed map is DERIVED from the tree at run time,
never hand-listed:

1. every tracked ``*.py`` file under ``src/entropic_substrate`` whose first line is
   the ``# Generated by gen_shims.py from ... -- do not hand-edit.`` marker and whose
   body contains ``import <landed dotted> as _target`` is a SHIM. Its own dotted
   address (derived from its path) maps to that target. The seven ENTRYPOINT shims
   additionally carry an ``if __name__ == "__main__": ... runpy.run_module(<target>,
   ...)`` block; its string argument must agree with ``_target`` or map derivation
   fails LOUD (disagreement is a structural defect, never silently resolved).
2. the re-export statements (``from entropic_substrate.<x> import name [as bound]``)
   in the ``__init__.py`` of the seven restored FACADE packages (P13-FACADE-NAMES),
   themselves discovered structurally: a direct subdirectory of
   ``src/entropic_substrate`` that is not a landed layer or ``__legacy``, whose
   ``__init__.py`` is NOT itself a generated shim, and that carries at least one
   top-level ``from entropic_substrate.<...> import ...`` statement. Map derivation
   fails LOUD unless exactly seven such packages are found.

Packages themselves (the eleven old directories, the root) have NO map entry.

Two subcommands:

``apply --root <root> <path>...``
    Rewrites every AST import form (``import X as Y``, ``from X import name(s)``,
    including the root form ``from entropic_substrate import <seg>``) and every
    resolvable non-docstring string-constant address it finds under the given
    paths, skipping whole files named in ``SKIP_LIST_B1`` and the specific
    ``RULED_B2_SITES`` lines. Computes every edit across the whole scope FIRST;
    if any AST import-form site fails to resolve (unmapped old name, ambiguous
    facade/shim collision, a facade name with no re-export, an unaliased
    ``import entropic_substrate.<old>...``, or a star import of an old address)
    the tool reports every such site and exits non-zero WITHOUT writing anything
    (fail LOUD, all-or-nothing). A string-constant site that does not resolve is
    left byte-identical and reported, never guessed. Idempotent: a second run
    over an already-rewritten tree produces a zero diff, because every subject
    predicate below is keyed on segments this run has already landed.

``verify --root <root> --mode {b1,b2} <path>...``
    Independent of the map (it runs to completion on a tree with zero shims and
    never derives or reads one): scans for old-address SITES by the same
    structural predicate (AST import targets, the root ``from entropic_substrate
    import <seg>`` form, and non-docstring string constants; in ``b2`` mode also
    a line-based, comment-skipping scan of the non-Python surfaces) and
    classifies every site found -- including inside skip-listed files, which it
    always scans too -- as one of SKIP (b1 mode only: file is on
    ``SKIP_LIST_B1``), BY_NAME (``NAMESPACE_EXCLUSIONS`` or
    ``WIRE_VALUE_EXCLUSIONS``), RULED (``RULED_B2_SITES``), EXCLUSION_DEF (the
    site is inside the source-level definition of one of this tool's own
    exclusion tables -- e.g. when this tool scans its own source), or UNLISTED.
    Exit 0 iff zero UNLISTED sites; exit 1 otherwise. In ``b1`` mode the residual
    is expected to equal the skip list plus the by-name exclusions (nothing
    else); in ``b2`` mode there is no skip list, only the by-name exclusions and
    exclusion-definition sites.

No ``assert`` statement appears in this module (bandit B101 fires on any
non-tests path in this repo's pre-commit hook). Stdlib only; no new dependency.
"""

