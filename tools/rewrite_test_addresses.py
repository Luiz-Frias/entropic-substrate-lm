def relpath(root: Path, path: Path) -> str:
    return path.resolve().relative_to(root.resolve()).as_posix()


def process_file_for_apply(
    root: Path, path: Path, text: str, shims: ShimMap, facades: FacadeMap
) -> tuple[list[Edit], list[UnmappedSite]]:
    rel = relpath(root, path)
    ruled_lines = RULED_B2_SITES.get(rel, frozenset())
    try:
        tree = ast.parse(text, filename=str(path))
    except SyntaxError as exc:
        return [], [UnmappedSite(rel, exc.lineno or 0, f"SyntaxError: {exc}")]
    idx = SourceIndex(text)
    doc_ids = docstring_node_ids(tree)
    edits: list[Edit] = []
    errors: list[UnmappedSite] = []

    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                name = alias.name
                if name == "entropic_substrate":
                    continue
                if not name.startswith("entropic_substrate."):
                    continue
                parts = name.split(".")
                if not is_old_seg(parts[1]):
                    continue
                if alias.lineno in ruled_lines:
                    continue
                if alias.asname is None:
                    errors.append(
                        UnmappedSite(
                            rel,
                            alias.lineno,
                            f"unaliased 'import {name}' of an old address (chained "
                            "attribute uses elsewhere would be stranded)",
                        )
                    )
                    continue
                if name not in shims:
                    errors.append(
                        UnmappedSite(
                            rel, alias.lineno, f"'import {name} as ...': no shim for {name!r}"
                        )
                    )
                    continue
                target = shims[name]
                start = idx.linecol_to_char(alias.lineno, alias.col_offset)
                end = start + len(name)
                edits.append(Edit(start, end, target))

        elif isinstance(node, ast.ImportFrom):
            if node.level and node.level > 0:
                continue
            module = node.module or ""
            if module != "entropic_substrate" and not module.startswith("entropic_substrate."):
                continue
            if module == "entropic_substrate":
                subject_names = [a for a in node.names if a.name == "*" or is_old_seg(a.name)]
                if not subject_names:
                    continue
                per_name = True
                whole_target = None
            else:
                top_seg = module.split(".")[1]
                if not is_old_seg(top_seg):
                    continue
                if node.lineno in ruled_lines:
                    continue
                if module in shims:
                    per_name = False
                    whole_target = shims[module]
                    subject_names = list(node.names)
                else:
                    # module is old but is not itself a shim key: it may
                    # still be a package (a facade, or an ordinary old
                    # directory with no re-exports) whose members are
                    # imported BY NAME as submodules -- resolve_name checks
                    # the shim-submodule form first, then facade re-exports,
                    # regardless of whether `module` happens to be one of
                    # the seven restored facades.
                    per_name = True
                    whole_target = None
                    subject_names = list(node.names)

            if not per_name:
                seg_start = idx.linecol_to_char(node.lineno, node.col_offset)
                seg_end = idx.linecol_to_char(node.end_lineno, node.end_col_offset)
                segment = text[seg_start:seg_end]
                m = re.match(r"(from\s+)(" + re.escape(module) + r")(\s+import)", segment)
                if m is None:
                    errors.append(
                        UnmappedSite(
                            rel, node.lineno, f"could not locate module span for {module!r}"
                        )
                    )
                    continue
                mod_start = seg_start + m.start(2)
                mod_end = seg_start + m.end(2)
                edits.append(Edit(mod_start, mod_end, whole_target))
                continue

            # per-name resolution (root "from entropic_substrate import <seg>"
            # or a facade package)
            groups: dict[str, list[tuple[ast.alias, str]]] = {}
            local_errors: list[UnmappedSite] = []
            for alias in subject_names:
                if alias.name == "*":
                    local_errors.append(
                        UnmappedSite(
                            rel, node.lineno, f"'from {module} import *' of an old address"
                        )
                    )
                    continue
                resolved = resolve_name(module, alias.name, shims, facades)
                if isinstance(resolved, tuple):
                    local_errors.append(
                        UnmappedSite(
                            rel, alias.lineno, f"'from {module} import {alias.name}': {resolved[1]}"
                        )
                    )
                    continue
                if resolved.kind == "submodule":
                    group_key = resolved.target_module
                else:
                    group_key = resolved.target_module
                bound = alias.asname if alias.asname else alias.name
                import_symbol = resolved.leaf
                new_alias_text = (
                    import_symbol if import_symbol == bound else f"{import_symbol} as {bound}"
                )
                groups.setdefault(group_key, []).append((alias, new_alias_text))

            if local_errors:
                errors.extend(local_errors)
                continue

            target_modules = list(groups.keys())
            if len(target_modules) == 1 and module != "entropic_substrate":
                # single target, module already correct shape for facades too:
                # only per-alias text may change (leaf rename / alias insert).
                target_mod = target_modules[0]
                same_module = target_mod == module
                if not same_module:
                    seg_start = idx.linecol_to_char(node.lineno, node.col_offset)
                    seg_end = idx.linecol_to_char(node.end_lineno, node.end_col_offset)
                    segment = text[seg_start:seg_end]
                    m = re.match(r"(from\s+)(" + re.escape(module) + r")(\s+import)", segment)
                    if m is None:
                        errors.append(
                            UnmappedSite(
                                rel, node.lineno, f"could not locate module span for {module!r}"
                            )
                        )
                        continue
                    mod_start = seg_start + m.start(2)
                    mod_end = seg_start + m.end(2)
                    edits.append(Edit(mod_start, mod_end, target_mod))
                for alias, new_text in groups[target_mod]:
                    a_start = idx.linecol_to_char(alias.lineno, alias.col_offset)
                    a_end = idx.linecol_to_char(alias.end_lineno, alias.end_col_offset)
                    edits.append(Edit(a_start, a_end, new_text))
            elif len(target_modules) == 1 and module == "entropic_substrate":
                target_mod = target_modules[0]
                seg_start = idx.linecol_to_char(node.lineno, node.col_offset)
                seg_end = idx.linecol_to_char(node.end_lineno, node.end_col_offset)
                segment = text[seg_start:seg_end]
                m = re.match(r"(from\s+)(entropic_substrate)(\s+import)", segment)
                if m is None:
                    errors.append(
                        UnmappedSite(rel, node.lineno, "could not locate root module span")
                    )
                    continue
                mod_start = seg_start + m.start(2)
                mod_end = seg_start + m.end(2)
                edits.append(Edit(mod_start, mod_end, target_mod))
                for alias, new_text in groups[target_mod]:
                    a_start = idx.linecol_to_char(alias.lineno, alias.col_offset)
                    a_end = idx.linecol_to_char(alias.end_lineno, alias.end_col_offset)
                    edits.append(Edit(a_start, a_end, new_text))
            else:
                # split: replace the whole statement with one line per target
                seg_start = idx.linecol_to_char(node.lineno, node.col_offset)
                seg_end = idx.linecol_to_char(node.end_lineno, node.end_col_offset)
                indent_match = re.match(r"[ \t]*", text[:seg_start][::-1])
                indent = indent_match.group(0)[::-1] if indent_match else ""
                lines_out = []
                for target_mod in target_modules:
                    names_text = ", ".join(t for _a, t in groups[target_mod])
                    lines_out.append(f"from {target_mod} import {names_text}")
                new_stmt = ("\n" + indent).join(lines_out)
                edits.append(Edit(seg_start, seg_end, new_stmt))

        elif isinstance(node, ast.Constant) and isinstance(node.value, str):
            if id(node) in doc_ids:
                continue
            if node.lineno in ruled_lines:
                continue
            segments = string_literal_segments(idx, text, node)
            if segments is None:
                continue
            for body_start, _body_end, body in segments:
                for m in CHAIN_RE.finditer(body):
                    chain = m.group(0)
                    parts = chain.split(".")
                    if len(parts) < 2:
                        continue
                    if not is_old_seg(parts[1]):
                        continue
                    if chain in WIRE_VALUE_EXCLUSIONS:
                        continue
                    resolved = longest_shim_prefix(chain, shims)
                    if resolved is None:
                        continue  # unresolved string: left byte-identical, reported by --verify
                    matched_prefix, target = resolved
                    tail = chain[len(matched_prefix) :]
                    replacement = target + tail
                    edits.append(Edit(body_start + m.start(), body_start + m.end(), replacement))

    return edits, errors


def iter_target_py_files(root: Path, args_paths: list[Path]) -> list[Path]:
    files: list[Path] = []
    seen: set[Path] = set()
    for p in args_paths:
        if p.is_dir():
            candidates = sorted(p.rglob("*.py"))
        else:
            candidates = [p]
        for c in candidates:
            if "__pycache__" in c.parts:
                continue
            rc = c.resolve()
            if rc in seen:
                continue
            seen.add(rc)
            rel = relpath(root, c)
            if rel in SKIP_LIST_B1:
                continue
            if rel in NAMESPACE_EXCLUSIONS:
                continue
            files.append(c)
    return files


def cmd_apply(args: argparse.Namespace) -> int:
    root = Path(args.root).resolve()
    try:
        shims, facades = build_map(root)
    except MapDerivationError as exc:
        print(f"MAP DERIVATION FAILED: {exc}", file=sys.stderr)
        return 1

    paths = [Path(p) for p in args.paths]
    files = iter_target_py_files(root, paths)

    per_file: dict[Path, tuple[str, list[Edit]]] = {}
    all_errors: list[UnmappedSite] = []
    for f in files:
        text = f.read_text(encoding="utf-8")
        edits, errors = process_file_for_apply(root, f, text, shims, facades)
        if errors:
            all_errors.extend(errors)
        if edits:
            per_file[f] = (text, edits)

    if all_errors:
        print(
            f"FAIL LOUD: {len(all_errors)} unresolved import-form site(s); nothing written.",
            file=sys.stderr,
        )
        for site in all_errors:
            print(f"  {site}", file=sys.stderr)
        return 1

    changed = 0
    for f, (text, edits) in per_file.items():
        new_text = apply_edits(text, edits)
        if new_text != text:
            f.write_text(new_text, encoding="utf-8")
            changed += 1

    print(
        f"apply: {changed} file(s) rewritten, {len(files)} scanned, 0 unresolved import-form sites."
    )
    return 0


