class MapDerivationError(Exception):
    """Map derivation found a structural defect (entrypoint disagreement, a
    facade count other than seven). Fails LOUD before any file is scanned."""


@dataclass
class UnmappedSite:
    path: str
    line: int
    detail: str

    def __str__(self) -> str:  # pragma: no cover - trivial formatting
        return f"{self.path}:{self.line}: {self.detail}"


class RewriteError(Exception):
    """One or more AST import-form sites failed to resolve. Carries every
    site found across the whole scope (fail LOUD is all-or-nothing, never
    the first hit)."""

    def __init__(self, sites: list[UnmappedSite]) -> None:
        self.sites = sites
        super().__init__("\n".join(str(s) for s in sites))


