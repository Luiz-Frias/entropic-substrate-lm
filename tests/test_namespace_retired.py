"""P13-POSTCONDITION: the old dotted namespace is RETIRED. RED at the B1
tip (recorded below), GREEN at B2.

Every check reads TRACKED content only -- ``git ls-files``, or a real
``Path`` walk over files this test itself enumerates -- never
``importlib.util.find_spec`` or bare directory ``.exists()``/``.is_dir()``
on the retired roots (architect constraint, REGIME-INDEPENDENT ASSERTIONS):
this checkout keeps ignored ``__pycache__`` residue for every deleted
directory, so a filesystem-existence or import-based check would read
GREEN here and RED in a clean clone. ``git ls-files`` sees only tracked
content in both regimes alike (P13-DRAFTER-DEVIATIONS: same mechanism as
``tests/test_legacy_empty.py:71``'s precedent).
"""

from __future__ import annotations

import subprocess
from pathlib import Path

import pytest

pytestmark = pytest.mark.unit

REPO_ROOT = Path(__file__).resolve().parents[1]

_RETIRED_DIRECTORIES = (
    "src/entropic_substrate/analysis",
    "src/entropic_substrate/data",
    "src/entropic_substrate/evidence",
    "src/entropic_substrate/experiments",
    "src/entropic_substrate/geometry",
    "src/entropic_substrate/init",
    "src/entropic_substrate/layers",
    "src/entropic_substrate/models",
    "src/entropic_substrate/observation",
    "src/entropic_substrate/predictive_state",
    "src/entropic_substrate/sentence_prediction",
)


def _git_ls_files(*pathspecs: str) -> list[str]:
    result = subprocess.run(
        ["git", "ls-files", "--", *pathspecs],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=True,
    )
    return [line for line in result.stdout.splitlines() if line]


def test_legacy_directory_has_no_tracked_files() -> None:
    tracked = _git_ls_files("src/entropic_substrate/__legacy")
    assert tracked == [], f"src/entropic_substrate/__legacy/ still has tracked files: {tracked}"


@pytest.mark.parametrize("directory", _RETIRED_DIRECTORIES)
def test_retired_directory_has_no_tracked_files(directory: str) -> None:
    tracked = _git_ls_files(directory)
    assert tracked == [], f"{directory} still has tracked files: {tracked}"


def test_zero_generated_by_gen_shims_markers_under_src_tests_tools_scripts() -> None:
    """P13-MARKER-SCOPE: scoped to src/, tests/, tools/, scripts/ -- prose
    files under .claude/, docs/ and .gitignore that quote the marker string
    are history, not subjects. This test file excludes itself (it quotes
    the marker string in its own module docstring history note, if it ever
    does)."""
    self_rel = Path(__file__).resolve().relative_to(REPO_ROOT).as_posix()
    offenders: list[str] = []
    for d in ("src", "tests", "tools", "scripts"):
        for rel in _git_ls_files(d):
            if rel == self_rel:
                continue
            path = REPO_ROOT / rel
            try:
                first_line = path.open(encoding="utf-8").readline()
            except (UnicodeDecodeError, OSError):
                continue
            if first_line.startswith("# Generated by gen_shims"):
                offenders.append(rel)
    assert offenders == [], f"generator marker(s) survived: {offenders}"


