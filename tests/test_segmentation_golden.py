"""Golden replay and guard teeth for ``segment_document``.

The fixture ``tests/fixtures/segmentation_golden.json`` holds the exact per-span
``(start, end, index)`` UTF-8 byte boundaries of every document the existing tests
segment (recorded from a full run of the eleven test files that call
``segment_document`` or ``prepare_documents``) plus literal documents chosen for
repeated sentences, whitespace placement and multi-byte text. The expectations were
generated by the segmenter at 391693b8, before sequential alignment existed, and are
never edited to follow a later segmenter. A change here is a change of segmentation
identity, not a fixture update.

Joining the spans back to the source cannot show a whitespace reallocation (the
partition type enforces coverage on every result), so the comparison is per span.
"""

import json
import re
from pathlib import Path
from types import SimpleNamespace
from typing import Any

import pytest
from tests.test_sentence_sampling import corpus

from entropic_substrate.core.sentence.records import SourceDocument
from entropic_substrate.core.sentence.segmentation import (
    OversizeDocument,
    SegmentationPolicy,
    SentenceSegmentation,
    segment_document,
)

pytestmark = pytest.mark.unit

GOLDEN_PATH = Path(__file__).parent / "fixtures" / "segmentation_golden.json"
INVALID = "segmenter produced invalid, altered, or overlapping spans"
OMITTED = "segmenter omitted non-whitespace source text"


def _golden() -> list[dict[str, Any]]:
    data = json.loads(GOLDEN_PATH.read_text(encoding="utf-8"))
    assert data["schema"] == "segmentation-golden-v1"
    return data["documents"]


def _spans_of(result: SentenceSegmentation | OversizeDocument) -> tuple[str, list[list[int]]]:
    if isinstance(result, OversizeDocument):
        return "oversize", [[result.span.start, result.span.end, result.span.index]]
    return "segmentation", [[span.start, span.end, span.index] for span in result.spans]


GOLDEN = _golden()


def test_the_golden_table_is_not_empty_and_has_unique_documents() -> None:
    assert len(GOLDEN) >= 80
    keys = [(row["text"], row["limit"]) for row in GOLDEN]
    assert len(keys) == len(set(keys))
    assert any(row["kind"] == "oversize" for row in GOLDEN)
    assert any(len(row["spans"]) > 1 for row in GOLDEN)


@pytest.mark.parametrize("row", GOLDEN, ids=[f"doc{i:03d}" for i in range(len(GOLDEN))])
def test_every_golden_document_replays_byte_identical_spans(row: dict[str, Any]) -> None:
    document = SourceDocument("golden", row["text"], "golden-v1")
    result = segment_document(document, SegmentationPolicy(row["limit"]))
    assert _spans_of(result) == (row["kind"], row["spans"])


def test_the_shared_sentence_fixture_corpus_replays_the_golden_spans() -> None:
    by_key = {(row["text"], row["limit"]): row for row in GOLDEN}
    records = corpus().records
    assert len(records) == 30
    for record in records:
        segmentation = record.segmentation
        row = by_key[(segmentation.document.text, segmentation.policy.max_sentence_bytes)]
        assert row["kind"] == "segmentation"
        assert segmentation.policy == SegmentationPolicy(64)
        assert _spans_of(segmentation) == ("segmentation", row["spans"])


def _stub(monkeypatch: pytest.MonkeyPatch, *parts: tuple[int, int, str]) -> None:
    outputs = [SimpleNamespace(start=start, end=end, sent=sent) for start, end, sent in parts]
    monkeypatch.setattr("pysbd.Segmenter.segment", lambda self, text: outputs)


@pytest.mark.parametrize(
    ("text", "parts"),
    [
        pytest.param(
            "Hello. World.",
            [(0, 7, "Hello. "), (0, 5, "Hello")],
            id="text-only-before-the-cursor",
        ),
        pytest.param(
            "Hello. World.",
            [(0, 7, "Hello. "), (7, 17, "Elsewhere.")],
            id="text-absent-from-the-document",
        ),
    ],
)
def test_a_sentence_text_absent_at_or_after_the_cursor_is_a_defect(
    monkeypatch: pytest.MonkeyPatch, text: str, parts: list[tuple[int, int, str]]
) -> None:
    _stub(monkeypatch, *parts)
    with pytest.raises(RuntimeError, match=f"^{re.escape(INVALID)}$"):
        segment_document(SourceDocument("fixture", text, "stub-v1"), SegmentationPolicy())


def test_non_whitespace_between_the_cursor_and_a_later_sentence_is_a_defect(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    # Both stubbed sentences carry their true offsets, so the invariant check cannot
    # fire first; only the coverage guard stands between "Oops. " and silence.
    text = "Hello. Oops. World."
    assert text[0:7] == "Hello. " and text[13:19] == "World."
    _stub(monkeypatch, (0, 7, "Hello. "), (13, 19, "World."))
    with pytest.raises(RuntimeError, match=f"^{re.escape(OMITTED)}$"):
        segment_document(SourceDocument("fixture", text, "stub-v1"), SegmentationPolicy())
