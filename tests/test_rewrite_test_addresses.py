def _facade(names_from: dict[str, str]) -> str:
    lines = ['"""facade."""', ""]
    for mod, name in names_from.items():
        lines.append(f"from {mod} import {name}")
    return "\n".join(lines) + "\n"


def test_discover_facades_requires_exactly_seven_RED(tmp_path: Path) -> None:
    root = _base_tree(tmp_path)
    _write(
        root / "src" / "entropic_substrate" / "data" / "__init__.py",
        _facade({"entropic_substrate.data.batching": "Corpus"}),
    )
    with pytest.raises(rta.MapDerivationError, match="exactly 7"):
        rta.discover_facades(root / "src")


def _seven_facades(root: Path) -> None:
    names = ["data", "geometry", "init", "layers", "models", "observation", "predictive_state"]
    for i, name in enumerate(names):
        _write(
            root / "src" / "entropic_substrate" / name / "__init__.py",
            _facade({f"entropic_substrate.{name}.mod{i}": f"Symbol{i}"}),
        )


def test_discover_facades_accepts_exactly_seven_GREEN_control(tmp_path: Path) -> None:
    root = _base_tree(tmp_path)
    _seven_facades(root)
    facades = rta.discover_facades(root / "src")
    assert len(facades) == 7
    assert facades["entropic_substrate.data"]["Symbol0"] == (
        "entropic_substrate.data.mod0",
        "Symbol0",
    )


def test_discover_facades_skips_a_marker_carrying_init_RED_control(tmp_path: Path) -> None:
    """A package __init__.py that is ITSELF a generated shim (marker on line
    1) is never mistaken for a hand-written facade, even if it re-exports."""
