def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(textwrap.dedent(text), encoding="utf-8")


def _shim(old_target_landed: str) -> str:
    return (
        "# Generated by gen_shims.py from .claude/workflows/landed-set -- do not hand-edit.\n"
        f"# Alias shim (test fixture) -> {old_target_landed}.\n"
        "import sys\n"
        "\n"
        f"import {old_target_landed} as _target\n"
        "\n"
        "sys.modules[__name__] = _target\n"
    )


def _entrypoint_shim(landed: str, runpy_target: str) -> str:
    return (
        "# Generated by gen_shims.py from .claude/workflows/landed-set -- do not hand-edit.\n"
        f"# Entrypoint alias shim (test fixture) -> {landed}.\n"
        'if __name__ == "__main__":\n'
        "    import runpy\n"
        "\n"
        f'    runpy.run_module("{runpy_target}", run_name="__main__", alter_sys=True)\n'
        "    raise SystemExit(0)\n"
        "import sys\n"
        "\n"
        f"import {landed} as _target\n"
        "\n"
        "sys.modules[__name__] = _target\n"
    )


def _base_tree(tmp_path: Path) -> Path:
    """A minimal src/entropic_substrate tree with the five landed packages
    present (as real, non-shim packages) so discover_facades' landed-name
    exclusion has something real to exclude."""
    root = tmp_path / "repo"
    for layer in ("kernel", "core", "ladder", "historical", "composition"):
        _write(root / "src" / "entropic_substrate" / layer / "__init__.py", '"""layer."""\n')
    _write(root / "src" / "entropic_substrate" / "__init__.py", '"""root."""\n')
    return root


