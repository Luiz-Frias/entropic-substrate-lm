def test_source_index_handles_multibyte_characters_before_the_match(tmp_path: Path) -> None:
    root = _apply_tree(tmp_path)
    test_file = root / "tests" / "test_x.py"
    # 'κ' is a 2-byte UTF-8 character preceding the import on the same line;
    # a byte-offset-as-char-offset bug would misplace the edit.
    _write(test_file, 'kappa = "κ"; import entropic_substrate.old_leaf as leaf\n')
    rc = rta.main(["apply", "--root", str(root), str(test_file)])
    assert rc == 0
    assert (
        test_file.read_text()
        == 'kappa = "κ"; import entropic_substrate.ladder.run.old_leaf as leaf\n'
    )
