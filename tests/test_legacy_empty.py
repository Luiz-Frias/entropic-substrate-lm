"""P12-LEGACY-EMPTY-DEF postcondition, mechanism form (P12-D4, conductor
2026-09-25): every file remaining under ``src/entropic_substrate/__legacy/``
carries the ``# Generated by gen_shims`` marker; the tracked set on disk
equals the generator's OWN derived forwarder set (never a hardcoded literal
count); every resolvable ``tools/mapping.json`` row (package keys excluded
by construction, P12-D3) is ``landed`` or ``retired``.

RED-first (house rule 5): the marker check runs through a shared
``_lacks_marker`` predicate, proven with its own guard-tooth test
(``test_marker_predicate_has_teeth``) against synthetic files under
``tmp_path`` -- RED on a file missing the marker, GREEN on one carrying it
-- rather than a self-contained plant under the live ``__legacy/`` tree,
which asserted only on what it had just written and never exercised the
real predicate (found by CodeRabbit review, 2026-09-25: the prior form
could not fail even with the real check inverted; proven by flip-test in a
scratch worktree before landing). A separate assertion confirms the tracked
set has no member outside the derived forwarder set.

LEGACY-EMPTY-DETERMINISM (architect constraint): enumerates TRACKED source
only (``git ls-files``), not a raw filesystem walk -- ``__legacy/__pycache__``
and friends survive `git rm` on disk and would make a raw walk lie, both
locally (stale .pyc) and never in a fresh clone (nothing tracked). The
expected set is DERIVED from gen_shims' own resolution
(``compute_expected_forwarder_map`` plus ``.pyi`` siblings for every
forwarder — the generator emits a typed stub beside every forwarder pair),
never a literal count, so it tracks reality across every one of p12's
6 commits without this file needing a per-commit edit. The predicate
guard-tooth test writes only under ``tmp_path``, never the live
``__legacy/`` tree, so it carries none of the shared-worktree hazard
(FOR-1542) the prior plant-based form did."""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
FRAGMENTS_DIR = REPO_ROOT / ".claude" / "workflows" / "landed-set"
MAPPING_PATH = REPO_ROOT / "tools" / "mapping.json"

TOOLS = REPO_ROOT / "tools"
if str(TOOLS) not in sys.path:
    sys.path.insert(0, str(TOOLS))
import gen_shims  # noqa: E402

pytestmark = pytest.mark.unit

GENERATED_MARKER = "# Generated by gen_shims.py"


def _lacks_marker(path: Path) -> bool:
    """True when ``path``'s first line is not the generated-shim marker --
    shared by the real tracked-file check and its own guard-tooth test, so
    a break in the predicate itself is caught by the latter (CodeRabbit
    review, 2026-09-25: the predicate this replaces was duplicated inline
    in a self-contained plant test that could never fail). Handles an empty
    file (``splitlines()`` on empty text is ``[]``) as lacking the marker,
    rather than raising ``IndexError``."""
    lines = path.read_text(encoding="utf-8").splitlines()
    return not lines or not lines[0].startswith(GENERATED_MARKER)


def _tracked_legacy_files() -> list[str]:
    """`git ls-files` under __legacy/, relative to the repo root -- TRACKED
    source only, never a raw `Path.rglob` (which would see stale
    __pycache__ contents that survive `git rm`, LEGACY-EMPTY-DETERMINISM)."""
    result = subprocess.run(
        ["git", "ls-files", "--", "src/entropic_substrate/__legacy/"],
        cwd=str(REPO_ROOT),
        capture_output=True,
        text=True,
        check=True,
    )
    return sorted(line for line in result.stdout.splitlines() if line)


def _resolved_modules() -> dict[str, dict]:
    mapping = gen_shims.load_mapping(MAPPING_PATH)
    fragments = gen_shims.load_fragments(FRAGMENTS_DIR)
    merged = gen_shims.merge_fragments(fragments, mapping)
    return gen_shims.resolve_all_modules(merged, mapping)


def _derived_expected_legacy_paths() -> set[str]:
    """The generator's own derived forwarder set (``.py`` targets) plus the
    typed ``.pyi`` stub sibling it emits beside every one -- never a literal
    count. Paths are relative to ``src/`` (as ``compute_expected_forwarder_map``
    returns them), re-based to repo-root-relative to match `_tracked_legacy_files`."""
    modules = _resolved_modules()
    out_dir = REPO_ROOT / "src"
    forwarders = gen_shims.compute_expected_forwarder_map(modules, out_dir)
    expected: set[str] = set()
    for rel in forwarders:
        expected.add(f"src/{rel}")
        expected.add(f"src/{rel[:-3]}.pyi" if rel.endswith(".py") else f"src/{rel}.pyi")
    return expected


def test_tracked_legacy_set_equals_the_generators_derived_forwarder_set() -> None:
    """The ACCEPTANCE-level equality: two independent derivations of "what
    should remain under __legacy/" must agree -- tracked files on disk vs.
    the generator's own live resolution -- with a non-vacuity guard."""
    tracked = set(_tracked_legacy_files())
    expected = _derived_expected_legacy_paths()
    assert tracked, "no tracked __legacy files found -- has git ls-files scope drifted?"
    assert expected, "generator derived zero expected forwarders -- resolution is broken"
    assert tracked == expected, (
        f"tracked __legacy set {sorted(tracked)} != generator-derived expected set "
        f"{sorted(expected)}"
    )


def test_every_tracked_legacy_file_carries_the_generated_marker() -> None:
    offenders = []
    for rel in _tracked_legacy_files():
        path = REPO_ROOT / rel
        assert path.is_file(), f"{rel} is tracked but missing on disk"
        if _lacks_marker(path):
            offenders.append(rel)
    assert not offenders, f"missing the generated marker as their first line: {offenders}"


def test_every_resolvable_mapping_row_is_landed_or_retired() -> None:
    """Package keys are excluded from resolve_all_modules by construction
    (P12-D3) -- every row this function DOES return must be landed or
    retired; nothing should remain in transit once p12's own tip lands."""
    modules = _resolved_modules()
    assert modules, "resolve_all_modules returned nothing -- resolution is broken"
    not_settled = {
        old: entry
        for old, entry in modules.items()
        if not entry.get("landed") and not entry.get("retired")
    }
    assert not not_settled, f"modules neither landed nor retired: {sorted(not_settled)}"


def test_marker_predicate_has_teeth(tmp_path: Path) -> None:
    """RED/GREEN guard-tooth for the SHARED ``_lacks_marker`` predicate
    itself (CodeRabbit review, 2026-09-25 -- the prior form asserted on a
    string it had just written and never called into the real check, so it
    could not fail; see the module docstring). Both arms run against
    ``tmp_path``, never the live ``__legacy/`` tree, so this test carries
    none of the shared-worktree hazard (FOR-1542) a live-tree plant would."""
    bad = tmp_path / "bad.py"
    bad.write_text("# not a generated marker\nvalue = 1\n")
    good = tmp_path / "good.py"
    good.write_text(f"{GENERATED_MARKER} from x\nimport sys\n")
    empty = tmp_path / "empty.py"
    empty.write_text("")
    assert _lacks_marker(bad), "RED arm: a file without the marker must be flagged"
    assert _lacks_marker(empty), "RED arm: an empty file must be flagged, not raise"
    assert not _lacks_marker(good), "GREEN arm: a file carrying the marker must not be flagged"


def test_expected_set_derivation_is_non_trivial_and_matches_the_measured_ten() -> None:
    """Non-regression sanity, not the source of truth (that's the equality
    test above): at p12's own tip the derived set is measured 10 files (the
    4 d1_* pairs from p8/p9 plus the evidence/ladder_campaign pair from
    p12's own commit 1), recorded here for legibility, never asserted as a
    literal in the real equality check above."""
    expected = _derived_expected_legacy_paths()
    assert len(expected) == 10, (
        f"expected forwarder set has {len(expected)} members, not the measured 10 -- "
        "if this is an intentional change, update this sanity note's own comment, "
        "never the equality test above"
    )
